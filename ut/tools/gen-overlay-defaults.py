#!/usr/bin/env python3
# Generates Source/Core/DolphinUT/OverlayDefaults.inc from the Android app's overlay defaults
# (stage 3.3, docs/ut-port/stage3.3-overlay.md), so that the Android app stays the one source:
#   - res/values/integers.xml: default positions (per mille of the screen, top-left corners);
#   - InputOverlay.kt: which integer is which control's position, per orientation and Wii Remote
#     variant (the "_H" sideways and "_O" upright keys);
#   - BooleanSetting.kt: the per-control show and latching settings ([AndroidOverlayButtons]).
# Usage: ut/tools/gen-overlay-defaults.py > Source/Core/DolphinUT/OverlayDefaults.inc
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

root = Path(__file__).resolve().parents[2]
android = root / "Source/Android/app/src/main"
kt = android / "java/org/dolphinemu/dolphinemu"

integers = {e.get("name"): int(e.text) for e in ET.parse(android / "res/values/integers.xml").getroot()
            if e.tag == "integer"}

overlay = (kt / "overlay/InputOverlay.kt").read_text()
positions = {}  # (button, variant, portrait) -> [x, y]
for func in re.finditer(r"private fun (\w+DefaultOverlay)\(\) \{(.*?)\n    \}\n", overlay, re.S):
    body = func.group(2)
    for m in re.finditer(r'ButtonType\.(\w+)\.toString\(\)\s*\+\s*(.*?)"(?:_([HO]))?-?([XY])"\s*,\s*'
                         r'resources\.getInteger\(R\.integer\.(\w+)\)', body, re.S):
        button, prefix, variant_in_string, axis, integer = m.groups()
        variant = variant_in_string or ("H" if '"_H"' in prefix else "O" if '"_O"' in prefix else "")
        portrait = "portrait" in prefix or "Portrait" in func.group(1)
        entry = positions.setdefault((button, variant, portrait), [None, None])
        entry[0 if axis == "X" else 1] = integers[integer]

settings = (kt / "features/settings/model/BooleanSetting.kt").read_text()
toggles = re.findall(r"MAIN_BUTTON_(TOGGLE|LATCHING)_(GC|WII|CLASSIC)_(\d+)\(\s*Settings\.FILE_DOLPHIN,\s*"
                     r"Settings\.SECTION_INI_ANDROID_OVERLAY_BUTTONS,\s*\"(\w+)\",\s*(true|false)", settings)

out = sys.stdout
out.write("// Generated by ut/tools/gen-overlay-defaults.py from the Android app's resources. Do not edit.\n\n")
out.write("// {ButtonType, variant (\"\", \"H\" sideways Wii Remote, \"O\" upright Wii Remote), portrait,\n")
out.write("//  x, y}: top-left corner in per mille of the screen (x of the long side in landscape).\n")
out.write("static constexpr OverlayDefaultPosition s_default_positions[] = {\n")
for (button, variant, portrait), (x, y) in sorted(positions.items()):
    if x is None or y is None:
        sys.exit(f"incomplete position for {button} {variant} {portrait}")
    out.write(f'    {{"{button}", "{variant}", {str(portrait).lower()}, {x}, {y}}},\n')
out.write("};\n\n")
out.write("// {kind, group, index, ini key, default}: [AndroidOverlayButtons] in Dolphin.ini.\n")
out.write("static constexpr OverlayButtonSetting s_button_settings[] = {\n")
for kind, group, index, key, default in toggles:
    out.write(f'    {{OverlayButtonSetting::{kind.capitalize()}, "{group}", {index}, "{key}", {default}}},\n')
out.write("};\n")
